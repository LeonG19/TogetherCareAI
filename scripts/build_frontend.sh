#!/usr/bin/env bash
# Build the React app for the SERVER deployment (web/server.js serving it on
# one origin), as opposed to the Cloudflare-Containers path where
# frontend/docker/entrypoint.sh does the equivalent at container startup.
#
#   ./scripts/build_frontend.sh
#
# Re-run after any change under frontend/src. web/server.js reads dist/ from
# disk per request, so a rebuild takes effect without restarting the service.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
NODE_BIN="${NODE_BIN:-/mnt/lagarza3/node/bin}"

if [[ ! -x "$NODE_BIN/npm" ]]; then
  echo "no npm at $NODE_BIN. Node was installed to /mnt/lagarza3/node (no root" >&2
  echo "needed); re-fetch it with:" >&2
  echo "  curl -fsSL https://nodejs.org/dist/v20.18.1/node-v20.18.1-linux-x64.tar.xz \\" >&2
  echo "    | tar -xJ -C /mnt/lagarza3/node --strip-components=1" >&2
  exit 1
fi
export PATH="$NODE_BIN:$PATH"

cd "$HERE/frontend"

if [[ ! -d node_modules ]]; then
  echo "==> npm ci"
  npm ci
fi

echo "==> npm run build"
npm run build

# Overwrite the copy vite lifted from public/, which carries the local-dev
# default of http://localhost:8000.
#
# BACKEND_URL="/api" is the whole point of the single-origin setup: the SPA
# calls back to whatever host it was loaded from, so the quick tunnel's
# hostname changing on restart needs no rebuild and no config edit.
#
# API_KEY stays EMPTY on purpose. getApiKey() returns undefined for "", so the
# browser sends no x-api-key at all and web/server.js attaches the real one
# server-side. Putting the key here would publish it to every visitor -- this
# file is page source.
cat > dist/env-config.js <<EOF
// Generated by scripts/build_frontend.sh for the on-server deployment.
// Do not edit by hand; re-run the script instead.
window.__ENV = {
  BACKEND_URL: "/api",
  API_KEY: "",
  AB_ENABLED: "${AB_ENABLED:-0}",
  AB_EVERY_N: "${AB_EVERY_N:-5}"
};
EOF

echo
echo "built $HERE/frontend/dist"
echo "  BACKEND_URL=/api  (same origin, no key in the bundle)"

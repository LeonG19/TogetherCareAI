#!/usr/bin/env bash
# Pin the public URL to a FIXED hostname using a Cloudflare *named* tunnel,
# replacing the quick tunnel that hands out a new random *.trycloudflare.com
# name on every restart.
#
#   ./scripts/setup_named_tunnel.sh togethercareai.yourdomain.com
#
# Prerequisite (run once, needs a browser - it prints a URL to open):
#   /home/lgarza3/bin/cloudflared tunnel login
# Pick the zone you want on the Cloudflare page; that writes ~/.cloudflared/cert.pem.
#
# Safe to re-run: it reuses an existing tunnel of the same name, and it backs
# up the current systemd unit so you can fall back to the quick tunnel with
#   ./scripts/setup_named_tunnel.sh --revert

set -euo pipefail

CFD=/home/lgarza3/bin/cloudflared
CFD_DIR="$HOME/.cloudflared"
UNIT_DIR="$HOME/.config/systemd/user"
UNIT="$UNIT_DIR/togethercare-tunnel.service"
BACKUP="$UNIT_DIR/togethercare-tunnel.service.quick-bak"
TUNNEL_NAME="${TUNNEL_NAME:-togethercare}"
LOCAL_PORT=8080   # the web tier: app + /api proxy + access gate. NOT the backend.
LOGDIR=/mnt/lagarza3/logs

die() { echo "ERROR: $*" >&2; exit 1; }

# --- revert path: put the quick tunnel back exactly as it was ---------------
if [[ "${1:-}" == "--revert" ]]; then
  [[ -f "$BACKUP" ]] || die "no backup at $BACKUP - nothing to revert to."
  cp "$BACKUP" "$UNIT"
  systemctl --user daemon-reload
  systemctl --user restart togethercare-tunnel
  echo "Reverted to the quick tunnel. New random URL in ~10s:"
  echo "  ./scripts/services.sh url"
  exit 0
fi

HOST="${1:-}"
[[ -n "$HOST" ]] || die "usage: $0 <hostname>   e.g. $0 togethercareai.yourdomain.com"
[[ "$HOST" == *.*.* || "$HOST" == *.* ]] || die "'$HOST' is not a fully-qualified hostname."
[[ "$HOST" != *trycloudflare.com ]] || die "trycloudflare.com names are quick-tunnel only and cannot be pinned."

# --- preflight -------------------------------------------------------------
[[ -x "$CFD" ]] || die "cloudflared not found at $CFD"
if [[ ! -f "$CFD_DIR/cert.pem" ]]; then
  die "not logged in to Cloudflare (no $CFD_DIR/cert.pem).
  Run this first, on a machine where you can open a browser link:
      $CFD tunnel login
  Choose the zone that '$HOST' belongs to, then re-run this script."
fi

echo "==> Using hostname : $HOST"
echo "==> Tunnel name    : $TUNNEL_NAME"
echo "==> Local origin   : http://localhost:$LOCAL_PORT (web tier)"
echo

# --- create (or reuse) the named tunnel ------------------------------------
UUID="$("$CFD" tunnel list --output json 2>/dev/null \
        | jq -r --arg n "$TUNNEL_NAME" '(. // []) | .[] | select(.name==$n) | .id' | head -1)"

if [[ -n "$UUID" && "$UUID" != "null" ]]; then
  echo "==> Reusing existing tunnel '$TUNNEL_NAME' ($UUID)"
else
  echo "==> Creating tunnel '$TUNNEL_NAME'"
  "$CFD" tunnel create "$TUNNEL_NAME"
  UUID="$("$CFD" tunnel list --output json \
          | jq -r --arg n "$TUNNEL_NAME" '(. // []) | .[] | select(.name==$n) | .id' | head -1)"
  [[ -n "$UUID" && "$UUID" != "null" ]] || die "could not determine tunnel UUID after create."
fi

CREDS="$CFD_DIR/$UUID.json"
[[ -f "$CREDS" ]] || die "credentials file missing: $CREDS"

# --- point the DNS record at the tunnel ------------------------------------
# Overwrites an existing record of the same name, which is what you want when
# re-pointing a hostname you have used before.
echo "==> Routing DNS $HOST -> $TUNNEL_NAME"
"$CFD" tunnel route dns --overwrite-dns "$TUNNEL_NAME" "$HOST"

# --- write the tunnel config ------------------------------------------------
# Only the web tier is published. 8010 (backend), 8001 (vLLM) and 8000/8002
# (ANOTHER USER'S services on this shared host) stay unreachable from outside.
echo "==> Writing $CFD_DIR/config.yml"
cat > "$CFD_DIR/config.yml" <<EOF
# Generated by scripts/setup_named_tunnel.sh - edit that script, not this file.
tunnel: $UUID
credentials-file: $CREDS

ingress:
  - hostname: $HOST
    service: http://localhost:$LOCAL_PORT
  - service: http_status:404
EOF

# --- swap the systemd unit over to the named tunnel -------------------------
[[ -f "$BACKUP" ]] || { [[ -f "$UNIT" ]] && cp "$UNIT" "$BACKUP" && echo "==> Backed up quick-tunnel unit -> $BACKUP"; }

echo "==> Rewriting $UNIT"
cat > "$UNIT" <<EOF
[Unit]
Description=TogetherCare cloudflared NAMED tunnel ($HOST -> web tier)
After=network.target togethercare-web.service
Wants=togethercare-web.service

[Service]
Type=simple
# Named tunnel: the hostname is FIXED and survives restarts, unlike the quick
# tunnel this replaced. Ingress rules live in $CFD_DIR/config.yml, which
# publishes ONLY localhost:$LOCAL_PORT (the web tier + access gate).
ExecStart=$CFD tunnel --no-autoupdate --config $CFD_DIR/config.yml run $TUNNEL_NAME

Restart=always
RestartSec=10

StandardOutput=append:$LOGDIR/tunnel.log
StandardError=append:$LOGDIR/tunnel.log

[Install]
WantedBy=default.target
EOF

systemctl --user daemon-reload
systemctl --user restart togethercare-tunnel

# --- verify -----------------------------------------------------------------
echo "==> Waiting for the tunnel to come up..."
for i in $(seq 1 30); do
  code="$(curl -s -o /dev/null -w '%{http_code}' --max-time 5 "https://$HOST/togethercareAI/web" || true)"
  if [[ "$code" == "200" ]]; then
    echo
    echo "SUCCESS - the public URL is now fixed at:"
    echo "  https://$HOST"
    echo "  Code: $(grep '^ACCESS_CODE=' /mnt/lagarza3/togethercare/web/.env | head -1 | cut -d= -f2-)"
    exit 0
  fi
  sleep 3
done

echo
echo "Tunnel restarted, but https://$HOST did not answer 200 within 90s."
echo "DNS may still be propagating. Check:"
echo "  tail -n 40 $LOGDIR/tunnel.log"
echo "  curl -sI https://$HOST"
echo "Roll back to the working quick tunnel at any time with:"
echo "  $0 --revert"
exit 1
